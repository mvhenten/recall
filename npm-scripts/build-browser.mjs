#!/usr/bin/env node
// Bundles browser/view.ts, the script the session page runs, into a string the Worker serves at
// /dashboard/transcript.js. It is a build step because the browser and the Worker share code —
// the turn reader the index runs, and the arithmetic of the walk — and a Worker cannot read its
// own source. The output is generated on install and before every deploy, never committed.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, "src", "transcript-view.generated.ts");

const bundled = await build({
  entryPoints: [join(ROOT, "browser", "view.ts")],
  bundle: true,
  format: "iife",
  target: "es2023",
  platform: "browser",
  write: false,
  logLevel: "warning",
});

const [output] = bundled.outputFiles;
if (!output) throw new Error("esbuild wrote no bundle for browser/view.ts");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// Generated by npm-scripts/build-browser.mjs from browser/view.ts. Do not edit.\nexport const TRANSCRIPT_SCRIPT = ${JSON.stringify(output.text)};\n`,
);
